package dev.bugcapsule.gradle

import java.io.File
import java.io.InputStream
import java.security.MessageDigest
import java.util.Properties
import java.util.UUID

/**
 * The debug-meta asset that the BugCapsule SDK reads at runtime
 * (`assets/bugcapsule-debug-meta.properties`, key `proguardUuid`).
 */
object DebugMeta {
    const val FILE_NAME = "bugcapsule-debug-meta.properties"
    const val PROGUARD_UUID_KEY = "proguardUuid"

    /**
     * Deterministic id of a mapping file: equal to `UUID.nameUUIDFromBytes(bytes)`
     * (an MD5, version 3 UUID), computed by streaming so large mappings are never
     * loaded in memory. Same mapping, same id.
     */
    fun proguardUuid(file: File): UUID = file.inputStream().buffered().use { proguardUuid(it) }

    fun proguardUuid(input: InputStream): UUID {
        val md5 = MessageDigest.getInstance("MD5")
        val buffer = ByteArray(64 * 1024)
        while (true) {
            val read = input.read(buffer)
            if (read < 0) break
            md5.update(buffer, 0, read)
        }
        val hash = md5.digest()
        hash[6] = ((hash[6].toInt() and 0x0f) or 0x30).toByte() // version 3
        hash[8] = ((hash[8].toInt() and 0x3f) or 0x80).toByte() // IETF variant
        var msb = 0L
        var lsb = 0L
        for (i in 0 until 8) msb = (msb shl 8) or (hash[i].toLong() and 0xff)
        for (i in 8 until 16) lsb = (lsb shl 8) or (hash[i].toLong() and 0xff)
        return UUID(msb, lsb)
    }

    /**
     * Content of the properties file. Written by hand rather than with
     * [Properties.store] so the output has no timestamp and is reproducible.
     */
    fun render(proguardUuid: UUID): String =
        "# Generated by the BugCapsule Gradle plugin. Do not edit.\n" +
            "$PROGUARD_UUID_KEY=${proguardUuid.toString().lowercase()}\n"

    /** Writes [FILE_NAME] into [directory] (created if needed) and returns the file. */
    fun write(directory: File, proguardUuid: UUID): File {
        directory.mkdirs()
        val file = File(directory, FILE_NAME)
        file.writeText(render(proguardUuid), Charsets.ISO_8859_1)
        return file
    }

    /** Reads the `proguardUuid` back from a file produced by [write]. */
    fun readProguardUuid(file: File): String {
        val properties = Properties()
        file.inputStream().use { properties.load(it) }
        return properties.getProperty(PROGUARD_UUID_KEY)?.trim()?.takeIf { it.isNotEmpty() }
            ?: throw IllegalStateException("$file has no $PROGUARD_UUID_KEY entry")
    }
}
