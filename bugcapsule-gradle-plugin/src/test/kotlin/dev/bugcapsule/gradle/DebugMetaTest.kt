package dev.bugcapsule.gradle

import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotEquals
import org.junit.Rule
import org.junit.Test
import org.junit.rules.TemporaryFolder
import java.io.File
import java.util.Properties
import java.util.UUID
import kotlin.random.Random

class DebugMetaTest {
    @get:Rule
    val tmp = TemporaryFolder()

    private val mapping = "com.example.Foo -> a.a:\n    void bar() -> a\n"

    @Test
    fun `uuid is deterministic and equals nameUUIDFromBytes`() {
        val file = tmp.newFile("mapping.txt").apply { writeText(mapping) }
        val first = DebugMeta.proguardUuid(file)
        val second = DebugMeta.proguardUuid(file)
        assertEquals(first, second)
        assertEquals(UUID.nameUUIDFromBytes(mapping.toByteArray()), first)
        assertEquals(3, first.version())
        assertEquals(2, first.variant())
    }

    @Test
    fun `uuid matches nameUUIDFromBytes for content larger than the read buffer`() {
        val bytes = Random(42).nextBytes(300_000)
        val file = tmp.newFile("big.txt").apply { writeBytes(bytes) }
        assertEquals(UUID.nameUUIDFromBytes(bytes), DebugMeta.proguardUuid(file))
    }

    @Test
    fun `uuid changes with content`() {
        val a = DebugMeta.proguardUuid(mapping.byteInputStream())
        val b = DebugMeta.proguardUuid((mapping + "# extra\n").byteInputStream())
        assertNotEquals(a, b)
    }

    @Test
    fun `properties file has the key and a lowercase dashed uuid`() {
        val uuid = UUID.fromString("0A1B2C3D-4E5F-3A6B-8C7D-8E9FA0B1C2D3")
        val dir = File(tmp.root, "out/assets")
        val file = DebugMeta.write(dir, uuid)

        assertEquals("bugcapsule-debug-meta.properties", file.name)
        assertEquals(dir, file.parentFile)
        val text = file.readText()
        assertEquals(
            "# Generated by the BugCapsule Gradle plugin. Do not edit.\n" +
                "proguardUuid=0a1b2c3d-4e5f-3a6b-8c7d-8e9fa0b1c2d3\n",
            text,
        )
        val properties = Properties().apply { file.inputStream().use { load(it) } }
        assertEquals("0a1b2c3d-4e5f-3a6b-8c7d-8e9fa0b1c2d3", properties.getProperty("proguardUuid"))
        assertEquals(1, properties.size)
        assertEquals("0a1b2c3d-4e5f-3a6b-8c7d-8e9fa0b1c2d3", DebugMeta.readProguardUuid(file))
    }

    @Test
    fun `writing twice is byte-identical`() {
        val uuid = DebugMeta.proguardUuid(mapping.byteInputStream())
        val a = DebugMeta.write(File(tmp.root, "a"), uuid).readBytes()
        val b = DebugMeta.write(File(tmp.root, "b"), uuid).readBytes()
        assertEquals(a.toList(), b.toList())
    }
}
